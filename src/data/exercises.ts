type Def = Omit<Exercise, "image" | "kind" | "bpCaution"> & {
  kind?: Exercise["kind"];
  bpCaution?: boolean;
  deviceName?: string;
};

function ex(d: Def): Exercise {
  const { deviceName, ...rest } = d;
  return {
    kind: "strength",
    bpCaution: false,
    ...rest,
    image: { url: null, source: null, deviceName: deviceName ?? d.nameEn, verification: "missing" },
  };
}

