/** تذكير حسب مستوى الألم المسجل. لا يغيّر البرنامج ولا يقرر أي علاج. */
export function painReminder(pain: number | null, baseline: number | null): string | null {
  if (pain == null) return null;
  if (pain >= 7) return "ألم مرتفع: أوقف هذه الحركة. إذا استمر الألم أو صاحبه تورم أو عدم قدرة على التحميل، اطلب تقييمًا متخصصًا.";
  if (baseline != null && pain - baseline >= 2) return "الألم زاد مقارنة ببداية الحصة: أوقف الحركة التي تزيد الألم، أو جرّب مدى أقصر/بديلًا بعد التحقق.";
  if (pain >= 4) return "ألم متوسط: لا تكمل الحركة إذا كانت تزيده. فكّر في تقليل المدى أو الوزن أو اختيار بديل.";
  return null;
}
